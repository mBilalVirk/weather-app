export function getWeatherInfo(code: number): WeatherCodeInfo {
  if (code in WMO_WEATHER_MAP) {
    return WMO_WEATHER_MAP[code];
  }
  // Fallback for unexpected code
  return {
    code,
    label: 'Variable conditions',
    description: 'Mixed atmospheric conditions',
    category: 'cloudy',
    dayIcon: Cloud,
    nightIcon: Cloud,
    gradientDark: 'from-slate-700/30 via-slate-800/40 to-slate-950',
    gradientLight: 'from-slate-200/50 via-slate-100/40 to-slate-50',
    accentColor: '#94a3b8',
    badgeBg: 'bg-slate-500/10 text-slate-300 border-slate-500/20',
  };
}

export function getWeatherDescription(code: number): string {
  return getWeatherInfo(code).label;
}

export function getWeatherIcon(code: number, isDay = true): LucideIcon {
  const info = getWeatherInfo(code);
  return isDay ? info.dayIcon : info.nightIcon;
}
